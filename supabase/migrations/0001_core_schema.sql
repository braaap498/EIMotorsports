-- =====================================================================
-- E&I Motorsports - core schema (Postgres / Supabase)
--
-- Design rules:
--   * The website is the source of truth. Nothing here is built around
--     eBay. Any marketplace (eBay included) is just a row in
--     sales_channels, with per-product links in channel_listings.
--   * Vehicle fitment is normalized: vehicles (model+year+submodel) and
--     product_fitment (product<->vehicle). Fast year/make/model lookups.
--   * Photos are stored in OUR storage (storage_path), never hotlinked.
--   * Every table has RLS enabled with NO policies: Supabase's public
--     API (anon/authenticated) can read nothing. Only the backend, which
--     connects with a server-side database role, can touch data.
-- =====================================================================

create extension if not exists pg_trgm with schema extensions;

-- ---------- helpers -------------------------------------------------
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

-- ---------- staff (back-office users; auth lives in Supabase Auth) ---
create table public.staff_profiles (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  display_name text not null unique,
  role         text not null default 'staff'
               check (role in ('owner','admin','staff')),
  is_active    boolean not null default true,
  created_at   timestamptz not null default now()
);

-- ---------- catalog taxonomy ----------------------------------------
create table public.categories (
  id          bigint generated by default as identity primary key,
  parent_id   bigint references public.categories(id) on delete set null,
  name        text not null,
  slug        text not null unique,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  unique (parent_id, name)
);

create table public.part_manufacturers (
  id    bigint generated by default as identity primary key,
  name  text not null unique,
  slug  text not null unique
);

-- ---------- vehicles & fitment --------------------------------------
create table public.vehicle_types (
  id    bigint generated by default as identity primary key,
  name  text not null unique,
  slug  text not null unique
);

create table public.vehicle_makes (
  id    bigint generated by default as identity primary key,
  name  text not null unique,
  slug  text not null unique
);

create table public.vehicle_models (
  id               bigint generated by default as identity primary key,
  make_id          bigint not null references public.vehicle_makes(id),
  vehicle_type_id  bigint references public.vehicle_types(id),
  name             text not null,
  slug             text not null,
  unique (make_id, name),
  unique (make_id, slug)
);

-- One row per sellable configuration: e.g. 2019 / Yamaha / YZ450F.
create table public.vehicles (
  id        bigint generated by default as identity primary key,
  model_id  bigint not null references public.vehicle_models(id),
  year      smallint not null check (year between 1900 and 2100),
  submodel  text,
  unique nulls not distinct (model_id, year, submodel)
);
create index vehicles_model_year_idx on public.vehicles (model_id, year);

-- ---------- products ------------------------------------------------
create table public.products (
  id                       bigint generated by default as identity primary key,
  sku                      text not null unique,
  slug                     text not null unique,
  title                    text not null,
  internal_part_number     text,
  manufacturer_part_number text,
  category_id              bigint references public.categories(id),
  part_manufacturer_id     bigint references public.part_manufacturers(id),
  part_type                text,
  -- technical attributes carried over from the desktop app
  bore_size_mm             numeric(6,2),
  shim_count               smallint,
  shim_od_mm               numeric(5,2),
  pressure_rating_bar      numeric(3,1),
  units_per_package        integer not null default 1 check (units_per_package > 0),
  -- barcode / labels
  barcode                  text unique,
  barcode_type             text,
  label_last_printed_at    timestamptz,
  -- money & stock
  list_price               numeric(10,2),
  cost                     numeric(10,2),
  quantity_on_hand         integer not null default 0,
  reorder_point            integer,
  -- shipping (needed for live carrier rates at checkout)
  weight_oz                numeric(8,2),
  length_in                numeric(6,2),
  width_in                 numeric(6,2),
  height_in                numeric(6,2),
  -- content
  condition                text,
  description              text,            -- sanitized HTML
  is_active                boolean not null default true,   -- exists in catalog
  is_published             boolean not null default false,  -- visible on website
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now()
);
create trigger products_updated_at before update on public.products
  for each row execute function public.set_updated_at();
create index products_category_idx  on public.products (category_id);
create index products_mfr_idx       on public.products (part_manufacturer_id);
create index products_published_idx on public.products (id) where is_published and is_active;
create index products_mpn_idx       on public.products (manufacturer_part_number);
create index products_title_trgm    on public.products using gin (title extensions.gin_trgm_ops);

create table public.product_photos (
  id            bigint generated by default as identity primary key,
  product_id    bigint not null references public.products(id) on delete cascade,
  storage_path  text not null,             -- path in our storage bucket
  source_url    text,                      -- where it was imported from, if anywhere
  is_primary    boolean not null default false,
  sort_order    integer not null default 0,
  created_at    timestamptz not null default now()
);
create index product_photos_product_idx on public.product_photos (product_id, sort_order);
create unique index product_photos_one_primary on public.product_photos (product_id) where is_primary;

create table public.product_item_specifics (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references public.products(id) on delete cascade,
  name        text not null,
  value       text not null,
  sort_order  integer not null default 0
);
create index product_specifics_product_idx on public.product_item_specifics (product_id, sort_order);

create table public.product_fitment (
  product_id  bigint not null references public.products(id) on delete cascade,
  vehicle_id  bigint not null references public.vehicles(id) on delete cascade,
  notes       text,
  primary key (product_id, vehicle_id)
);
create index product_fitment_vehicle_idx on public.product_fitment (vehicle_id, product_id);

-- ---------- inventory ledger ----------------------------------------
create table public.inventory_transactions (
  id               bigint generated by default as identity primary key,
  product_id       bigint not null references public.products(id),
  transaction_type text not null
                   check (transaction_type in ('Receive','Sale','Adjustment','Return','Breakage')),
  quantity_change  integer not null,
  reference        text,
  created_by       uuid references public.staff_profiles(user_id),
  created_at       timestamptz not null default now()
);
create index inventory_tx_product_idx on public.inventory_transactions (product_id, created_at desc);

-- ---------- purchasing ----------------------------------------------
create table public.vendors (
  id            bigint generated by default as identity primary key,
  name          text not null unique,
  contact_info  text,
  is_active     boolean not null default true
);

create table public.purchase_orders (
  id                bigint generated by default as identity primary key,
  vendor_id         bigint references public.vendors(id),
  order_date        timestamptz not null default now(),
  received_date     timestamptz,
  reference_number  text,
  created_by        uuid references public.staff_profiles(user_id)
);

create table public.purchase_order_lines (
  id                  bigint generated by default as identity primary key,
  purchase_order_id   bigint not null references public.purchase_orders(id) on delete cascade,
  product_id          bigint not null references public.products(id),
  quantity_ordered    integer not null check (quantity_ordered > 0),
  quantity_received   integer not null default 0 check (quantity_received >= 0),
  unit_cost           numeric(10,2) not null
);
create index po_lines_po_idx on public.purchase_order_lines (purchase_order_id);

-- ---------- sales channels (website is just the first one) ----------
create table public.sales_channels (
  id         bigint generated by default as identity primary key,
  name       text not null unique,
  is_active  boolean not null default true
);
insert into public.sales_channels (name) values ('Website'), ('eBay'), ('In Person')
on conflict (name) do nothing;

-- Optional link between a product and a listing on an outside channel.
-- This is the ONLY place marketplace ids live. Drop a channel and the
-- core catalog is untouched.
create table public.channel_listings (
  id               bigint generated by default as identity primary key,
  product_id       bigint not null references public.products(id) on delete cascade,
  channel_id       bigint not null references public.sales_channels(id),
  external_id      text,
  external_url     text,
  status           text not null default 'draft' check (status in ('draft','active','ended')),
  price_override   numeric(10,2),
  last_synced_at   timestamptz,
  unique (product_id, channel_id),
  unique (channel_id, external_id)
);

create table public.sales_transactions (
  id                        bigint generated by default as identity primary key,
  product_id                bigint not null references public.products(id),
  channel_id                bigint references public.sales_channels(id),
  quantity_sold             integer not null check (quantity_sold > 0),
  unit_sale_price           numeric(10,2) not null,
  unit_cost_at_sale         numeric(10,2),
  shipping_charged          numeric(10,2),
  shipping_cost             numeric(10,2),
  platform_fees             numeric(10,2),
  sale_date                 timestamptz not null default now(),
  order_reference           text,
  inventory_transaction_id  bigint references public.inventory_transactions(id),
  ship_to_state             text,
  ship_to_zip               text
);
create index sales_date_idx    on public.sales_transactions (sale_date);
create index sales_product_idx on public.sales_transactions (product_id);

-- ---------- integrations (generic; eBay, Stripe webhooks, etc.) -----
create table public.integration_settings (
  provider    text primary key,
  settings    jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now()
);

-- Tokens are encrypted by the backend (Fernet) before they are stored.
create table public.integration_credentials (
  provider    text primary key,
  ciphertext  text not null,
  updated_at  timestamptz not null default now()
);

-- ---------- lock down the public API --------------------------------
-- Supabase exposes everything in `public` through its REST API. RLS on
-- with zero policies = deny all for anon/authenticated.
do $$
declare t record;
begin
  for t in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', t.tablename);
  end loop;
end $$;

revoke all on all tables    in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
alter default privileges in schema public revoke all on tables    from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;
