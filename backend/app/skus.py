"""Product identifiers, in one place.

products.ebay_item_id    the eBay item number the part came from, e.g. EBAY-178554199250 (optional; the
                         full list of eBay listings for a part lives in channel_listings)
products.sku             OUR in-house SKU, EI-0000001, EI-0000002 ... Every product has one. Until the
                         numbers are assigned (after the clean-up merging) every product holds the
                         placeholder EI-0000000. New products get the next number from the database.
products.sku_display     generated by the database: the real SKU once assigned, otherwise the eBay item
                         number. Screens that list parts show this, so they are never full of EI-0000000.
products.custom_label_sku  the eBay "custom label" text (e.g. 9144PSxx120558xx120216). Optional.
Shelf barcode labels are EIB- plus the same 7 digits as the SKU (EI-0000123 -> EIB-0000123).
"""
from typing import Optional

PLACEHOLDER_SKU = "EI-0000000"
SKU_PREFIX = "EI-"
SHELF_PREFIX = "EIB-"


def is_assigned(sku: Optional[str]) -> bool:
    return bool(sku) and sku != PLACEHOLDER_SKU


def shelf_code_for(sku: Optional[str]) -> Optional[str]:
    """EIB-0000123 for EI-0000123, or None while the part still has the placeholder SKU."""
    if not is_assigned(sku) or not str(sku).startswith(SKU_PREFIX):
        return None
    return SHELF_PREFIX + str(sku)[len(SKU_PREFIX):]


def clean_ebay_item_id(raw: Optional[str]) -> Optional[str]:
    """Blank -> None. A bare item number gets the EBAY- prefix; anything else is kept as typed."""
    v = (raw or "").strip()
    if not v:
        return None
    if v.isdigit():
        return "EBAY-" + v
    if v.upper().startswith("EBAY-"):
        return "EBAY-" + v[5:]
    return v
